// Static site generation: the precompiled viewer, the resolved data, the icons of collections used and
// the local icons. The output directory is only ever emptied if a previous build created it.
import { cp, mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { buildViewerData, loadArchitecture, VERSION, type ConfigError, type ViewerBundle } from '../core/index.ts'
import { DATA_FILE, FILES_DIR, localFiles } from './site.ts'

/** Marks a directory as generated, so that the next build may replace it. */
export const BUILD_MARKER = '.graphinity'

export interface BuildOptions {
  file: string
  projectRoot: string
  outDir: string
  viewerDir: string
}

export type BuildResult =
  | { ok: true; outDir: string; files: number; bundle: ViewerBundle }
  | { ok: false; errors: ConfigError[] }
  /** The output directory cannot be used; nothing was written. */
  | { ok: false; refused: string }

export async function buildSite({ file, projectRoot, outDir, viewerDir }: BuildOptions): Promise<BuildResult> {
  const out = path.resolve(outDir)
  const refused = await checkOutput(out, [
    ['the project directory', projectRoot],
    ['the working directory', process.cwd()],
    ['the viewer', viewerDir],
  ])
  if (refused) return { ok: false, refused }

  const result = await loadArchitecture(file, { projectRoot })
  if (!result.ok) return { ok: false, errors: result.errors }
  const bundle = await buildViewerData(result.architecture)

  await rm(out, { recursive: true, force: true })
  await mkdir(out, { recursive: true })
  await cp(viewerDir, out, { recursive: true })
  await writeFile(path.join(out, DATA_FILE), JSON.stringify(bundle.data))
  // Icons of collections (only those used), their attributions and licenses.
  for (const [file, content] of Object.entries(bundle.files)) {
    await mkdir(path.dirname(path.join(out, file)), { recursive: true })
    await writeFile(path.join(out, file), content)
  }
  const icons = localFiles(result.architecture)
  for (const icon of icons) {
    // Icon paths come from the loader: relative, inside the project, existing.
    const target = path.join(out, FILES_DIR, icon)
    await mkdir(path.dirname(target), { recursive: true })
    await writeFile(target, await readFile(path.join(projectRoot, icon)))
  }
  await writeFile(path.join(out, BUILD_MARKER), `Generated by graphinity ${VERSION}. Replaced on every build.\n`)

  return { ok: true, outDir: out, files: await countFiles(out), bundle }
}

/** Why `out` cannot be (re)generated, if it cannot. */
async function checkOutput(out: string, protectedPaths: [string, string][]): Promise<string | undefined> {
  for (const [name, protectedPath] of protectedPaths) {
    const resolved = path.resolve(protectedPath)
    if (isWithin(out, resolved)) return `The output directory would contain ${name} (${resolved}).`
    if (name === 'the viewer' && isWithin(resolved, out)) return `The output directory is inside ${name} (${resolved}).`
  }
  let entries: string[]
  try {
    if (!(await stat(out)).isDirectory()) return `${out} exists and is not a directory.`
    entries = await readdir(out)
  } catch {
    return undefined // Does not exist yet.
  }
  if (entries.length > 0 && !entries.includes(BUILD_MARKER)) {
    return `${out} is not empty and was not created by graphinity. Remove it or choose another --out.`
  }
  return undefined
}

/** True if `inner` is `outer` or inside it. */
function isWithin(outer: string, inner: string): boolean {
  const relative = path.relative(outer, inner)
  return relative === '' || (!relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative))
}

async function countFiles(dir: string): Promise<number> {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true })
  return entries.filter((entry) => entry.isFile()).length
}
